_OUTLINES = {"claude": CLAUDE_OUTLINE, "codex": CODEX_OUTLINE, "copilot": COPILOT_OUTLINE}
KINDS = tuple(_OUTLINES)


def brand_color(kind, foreground):
    """Claude keeps its orange; Codex and Copilot are monochrome and follow the text colour."""
    return CLAUDE_ORANGE if kind == "claude" else foreground


def draw_mark(ctx, kind, size, rgb, x=0.0, y=0.0):
    """Fill `kind`'s mark into the size x size square at (x, y)."""
    outline = _OUTLINES.get(kind)
    if outline is None:
        return
    import cairo     # callers only reach this with cairo available

    tokens = outline.split()
    ctx.save()
    ctx.translate(x, y)
    ctx.scale(size / 24.0, size / 24.0)
    ctx.new_path()
    i = 0
    while i < len(tokens):
        op = tokens[i]
        i += 1
        if op == "M":
            ctx.move_to(float(tokens[i]), float(tokens[i + 1]))
            i += 2
        elif op == "L":
            ctx.line_to(float(tokens[i]), float(tokens[i + 1]))
            i += 2
        elif op == "C":
            ctx.curve_to(*(float(t) for t in tokens[i:i + 6]))
            i += 6
        elif op == "Z":
            ctx.close_path()
    ctx.set_fill_rule(cairo.FILL_RULE_EVEN_ODD)
    ctx.set_source_rgb(*rgb)
    ctx.fill()
    ctx.restore()
